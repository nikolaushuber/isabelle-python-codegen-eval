"""
Adapter between the module generated by the Isabelle Python backend and a plain
persistent-map interface used by the tests.

Everything that depends on how the backend represents Isabelle values lives in
this file. Run `python probe.py` to see what the generated code actually returns,
then adjust the decoders below if needed.

Environment:
  SPLAY_GEN_PATH    directory containing the generated module (default ../isabelle/generated)
  SPLAY_GEN_MODULE  module name (default splay_ref)
"""
import importlib
import inspect
import os
import sys
from dataclasses import fields, is_dataclass
from typing import List, Optional, Tuple

HERE = os.path.dirname(os.path.abspath(__file__))
GEN_PATH = os.environ.get("SPLAY_GEN_PATH", os.path.join(HERE, "..", "isabelle", "generated"))
GEN_MODULE = os.environ.get("SPLAY_GEN_MODULE", "splay_ref")

if GEN_PATH not in sys.path:
    sys.path.insert(0, GEN_PATH)
gen = importlib.import_module(GEN_MODULE)

# Constructor names the decoders treat as option/list constructors.
_SOME = {"Some"}
_NONE = {"None_", "Nonea", "NONE", "Nothing"}
_CONS = {"Cons"}
_NIL = {"Nil"}


def _arity(f) -> Optional[int]:
    try:
        sig = inspect.signature(f)
    except (TypeError, ValueError):
        return None
    params = [p for p in sig.parameters.values()
              if p.kind in (p.POSITIONAL_ONLY, p.POSITIONAL_OR_KEYWORD) and p.default is p.empty]
    if any(p.kind == p.VAR_POSITIONAL for p in sig.parameters.values()):
        return None
    return len(params)


def _apply(f, *args):
    """Call f either uncurried f(a, b) or curried f(a)(b), depending on its arity."""
    n = _arity(f)
    if n is None or n == len(args):
        return f(*args)
    r = f
    for a in args:
        r = r(a)
    return r


def _fields(x) -> list:
    if is_dataclass(x) and not isinstance(x, type):
        return [getattr(x, f.name) for f in fields(x)]
    if isinstance(x, tuple):
        return list(x)
    slots = getattr(type(x), "__slots__", None)
    if slots:
        slots = [slots] if isinstance(slots, str) else list(slots)
        return [getattr(x, s) for s in slots]
    return list(vars(x).values())


def decode_option(x):
    if x is None or type(x).__name__ in _NONE:
        return None
    if type(x).__name__ in _SOME:
        return _fields(x)[0]
    raise TypeError(f"cannot decode option value {x!r} of type {type(x).__name__}")


def decode_list(x) -> list:
    if isinstance(x, (list, tuple)):
        return list(x)
    out = []
    while True:
        name = type(x).__name__
        if name in _NIL:
            return out
        if name in _CONS:
            head, x = _fields(x)
            out.append(head)
        else:
            raise TypeError(f"cannot decode list value {x!r} of type {name}")


def decode_pair(x) -> Tuple[int, int]:
    f = _fields(x)
    if len(f) != 2:
        raise TypeError(f"cannot decode pair {x!r}")
    return (f[0], f[1])


def _const(name):
    v = getattr(gen, name)
    if callable(v) and _arity(v) == 0:
        v = v()
    return v


class GoldenSplay:
    """Persistent int->int map backed by the generated Isabelle splay tree."""

    __slots__ = ("_t",)

    def __init__(self, t):
        self._t = t

    @staticmethod
    def empty() -> "GoldenSplay":
        return GoldenSplay(_const("m_empty"))

    def update(self, k: int, v: int) -> "GoldenSplay":
        return GoldenSplay(_apply(gen.m_update, k, v, self._t))

    def delete(self, k: int) -> "GoldenSplay":
        return GoldenSplay(_apply(gen.m_delete, k, self._t))

    def lookup(self, k: int) -> Optional[int]:
        return decode_option(_apply(gen.m_lookup, self._t, k))

    def items(self) -> List[Tuple[int, int]]:
        return [decode_pair(p) for p in decode_list(_apply(gen.m_items, self._t))]

    @property
    def raw(self):
        return self._t
