"""
Benchmark: Isabelle-generated reference implementations vs the Python libraries they are tested
against, over a range of input sizes.

Each benchmark runs the same workload on both sides, checks that the results agree, and records
the median wall-clock time, the interquartile range, the fastest and slowest repeat, and every
timed run. A side that fails (e.g. a RecursionError in the generated code) is recorded as failed
for that size and is not run on larger sizes.
A side whose median exceeds the time budget is not run on larger sizes either.

Results go to bench/out/<interpreter>/results.json (cpython or pypy), so runs under different
interpreters sit side by side; bench/plot.py compares them. The Makefile wraps both
environments (`make bench`, `make bench-pypy`, `make plot`). Directly, from the repository root
after `isabelle build -c -D .`:

    uv run python bench/run.py                 # all benchmarks
    uv run python bench/run.py --quick         # smaller sizes
    uv run python bench/run.py --only rbt_map hermite
    UV_PROJECT_ENVIRONMENT=.venv-pypy uv run --python pypy@3.11 --no-dev python bench/run.py
"""
import argparse
import heapq
import importlib
import json
import os
import platform
import random
import statistics
import sys
import time
from dataclasses import dataclass
from typing import Any, Callable

# imported up front, so that no measurement includes an import
from sortedcontainers import SortedDict
from sympy import Matrix, ZZ
from sympy.matrices.normalforms import hermite_normal_form, smith_normal_form

from common import INTERPRETER, MATRIX_LABEL, OUT, ROOT, is_matrix

# where the generated modules are read from: <folder>/generated by default, or
# <GENERATED>/<folder> with --generated (bench/caching.py keeps one copy per build)
GENERATED = None


def load(folder, module):
    path = os.path.join(GENERATED, folder) if GENERATED else os.path.join(ROOT, folder, "generated")
    sys.path.insert(0, path)
    return importlib.import_module(module)


# Each benchmark: make(n, rng) -> input; ref(input) and lib(input) -> comparable results.

@dataclass
class Bench:
    name: str
    label: str            # what one unit of size means, for the x axis
    sizes: list
    quick_sizes: list
    make: Callable[[int, random.Random], Any]
    ref: Callable[[Any], Any]
    lib: Callable[[Any], Any]
    lib_name: str

    @property
    def matrix(self):
        return is_matrix(self.label)


def make_map_input(n, rng):
    keys = list(range(n))
    rng.shuffle(keys)
    return keys


def map_ref(empty, update, lookup, delete, items):
    """Insert all keys, look all up, delete every other one, list the items."""
    def run(keys):
        t = empty
        for k in keys:
            t = update(k, -k, t)
        found = [lookup(t, k) for k in keys]
        for k in keys[::2]:
            t = delete(k, t)
        return found, list(items(t))
    return run


def map_lib(keys):
    d = SortedDict()
    for k in keys:
        d[k] = -k
    found = [d.get(k) for k in keys]
    for k in keys[::2]:
        del d[k]
    return found, list(d.items())


def make_heap_input(n, rng):
    return [rng.randint(-10**6, 10**6) for _ in range(n)]


def heap_ref(gen):
    def run(xs):
        t = gen.h_empty()
        for x in xs:
            t = gen.h_insert(x, t)
        out = []
        while (m := gen.h_get_min(t)) is not None:
            out.append(m)
            t = gen.h_del_min(t)
        return out
    return run


def heap_lib(xs):
    h = []
    for x in xs:
        heapq.heappush(h, x)
    return [heapq.heappop(h) for _ in range(len(h))]


def make_matrix(n, rng):
    return [[rng.randint(-10, 10) for _ in range(n)] for _ in range(n)]


def rot180(m):
    return [row[::-1] for row in m[::-1]]


def transpose(m):
    return [list(c) for c in zip(*m)]


def hnf_ref(gen):
    def run(a):
        # SymPy convention (see hermite/test_hermite_diff.py)
        au = transpose(rot180(gen.hnf_rows(rot180(transpose(a)))))
        cols = [c for c in transpose(au) if any(c)]
        return transpose(cols) if cols else [[] for _ in a]
    return run


def hnf_lib(a):
    h = hermite_normal_form(Matrix(a))
    return [[int(x) for x in h.row(i)] for i in range(h.rows)] if h.cols else [[] for _ in a]


def snf_ref(gen):
    def run(a):
        _, (s, _) = gen.snf(len(a[0]), a)
        return [abs(s[i][i]) for i in range(min(len(s), len(s[0])))]
    return run


def snf_lib(a):
    s = smith_normal_form(Matrix(a), domain=ZZ)
    return [int(s[i, i]) for i in range(min(s.rows, s.cols))]


def benchmarks():
    splay = load("splay_tree", "Splay_Ref")
    rbt = load("rbt_map", "RBT_Map_Ref")
    lheap = load("leftist_heap", "Leftist_Heap_Ref")
    bheap = load("binomial_heap", "Binomial_Heap_Ref")
    herm = load("hermite", "Hermite_Ref")
    smith = load("smith", "Smith_Ref")
    elems = [100, 300, 1000, 3000, 10000, 30000]
    quick_elems = [100, 300, 1000, 3000]
    dims = [1, 2, 3, 4, 5, 6, 7, 8]
    quick_dims = [1, 2, 3, 4, 5]
    return [
        Bench("splay_tree", "keys", elems, quick_elems, make_map_input,
              map_ref(splay.m_empty(), splay.m_update, splay.m_lookup, splay.m_delete, splay.m_items),
              map_lib, "SortedDict"),
        Bench("rbt_map", "keys", elems, quick_elems, make_map_input,
              map_ref(rbt.r_empty(), rbt.r_update, rbt.r_lookup, rbt.r_delete, rbt.r_items),
              map_lib, "SortedDict"),
        Bench("leftist_heap", "elements", elems, quick_elems, make_heap_input,
              heap_ref(lheap), heap_lib, "heapq"),
        Bench("binomial_heap", "elements", elems, quick_elems, make_heap_input,
              heap_ref(bheap), heap_lib, "heapq"),
        Bench("hermite", MATRIX_LABEL, dims, quick_dims, make_matrix,
              hnf_ref(herm), hnf_lib, "sympy HNF"),
        Bench("smith", MATRIX_LABEL, dims, quick_dims, make_matrix,
              snf_ref(smith), snf_lib, "sympy SNF"),
    ]


def time_side(fn, arg, repeats, warmup):
    """
    `warmup` untimed runs (PyPy's JIT needs several runs to compile the hot loops, and warming up
    keeps one-time costs out), then `repeats` timed runs.
    """
    for _ in range(warmup):
        fn(arg)
    times = []
    for _ in range(repeats):
        t0 = time.perf_counter()
        result = fn(arg)
        times.append(time.perf_counter() - t0)
    return times, result


def run_bench(b, sizes, budget, repeats, warmup, seed):
    rows = []
    stopped = {"reference": None, "library": None}
    for n in sizes:
        arg = b.make(n, random.Random(f"{seed}-{b.name}-{n}"))
        results = {}
        for side, fn in (("reference", b.ref), ("library", b.lib)):
            if stopped[side]:
                rows.append({"size": n, "side": side, "status": "skipped", "reason": stopped[side]})
                continue
            try:
                times, result = time_side(fn, arg, repeats, warmup)
            except RecursionError:
                stopped[side] = "recursion limit"
                rows.append({"size": n, "side": side, "status": "failed", "reason": "recursion limit"})
                continue
            results[side] = result
            median = statistics.median(times)
            q1, _, q3 = statistics.quantiles(times, n=4)
            rows.append({"size": n, "side": side, "status": "ok", "seconds": median,
                         "q1_seconds": q1, "q3_seconds": q3,
                         "min_seconds": min(times), "max_seconds": max(times), "repeats": len(times),
                         "times": times})
            if median > budget:
                stopped[side] = f"over {budget:g} s budget"
        if len(results) == 2 and results["reference"] != results["library"]:
            raise AssertionError(f"{b.name} n={n}: reference and library disagree")
        line = "  ".join(
            f"{r['side']}={r['seconds'] * 1000:9.2f} ms" if r["status"] == "ok" else f"{r['side']}={r['status']:>12}"
            for r in rows if r["size"] == n)
        print(f"{b.name:14} {n:>6}  {line}", flush=True)
    return rows


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--only", nargs="+", help="benchmark names to run")
    p.add_argument("--quick", action="store_true", help="smaller sizes")
    p.add_argument("--budget", type=float, default=5.0,
                   help="stop growing a side once its median exceeds this many seconds (default 5)")
    p.add_argument("--repeats", type=int, default=15,
                   help="timed runs per measurement (default 15)")
    p.add_argument("--warmup", type=int, default=10,
                   help="untimed warm-up runs before each measurement (default 10)")
    p.add_argument("--seed", default="0")
    p.add_argument("--out", help=f"output directory (default bench/out/{INTERPRETER})")
    p.add_argument("--generated", help="read the generated modules from GENERATED/<folder> "
                   "instead of <folder>/generated")
    p.add_argument("--label", help="free-form label stored in results.json, e.g. the build variant")
    args = p.parse_args()

    global GENERATED
    GENERATED = args.generated and os.path.abspath(args.generated)

    out = args.out or os.path.join(OUT, INTERPRETER)
    os.makedirs(out, exist_ok=True)
    json_path = os.path.join(out, "results.json")
    results = {"interpreter": INTERPRETER, "python": sys.version.split()[0],
               "implementation_version": platform.python_version() if INTERPRETER == "cpython"
               else ".".join(map(str, sys.pypy_version_info[:3])),
               "recursion_limit": sys.getrecursionlimit(), "benchmarks": []}
    if args.label:
        results["label"] = args.label
    print(f"{INTERPRETER} {results['implementation_version']} (Python {results['python']})", flush=True)
    for b in benchmarks():
        if args.only and b.name not in args.only:
            continue
        rows = run_bench(b, b.quick_sizes if args.quick else b.sizes, args.budget,
                         args.repeats, args.warmup, args.seed)
        results["benchmarks"].append({"name": b.name, "label": b.label, "lib_name": b.lib_name,
                                      "rows": rows})
    with open(json_path, "w") as f:
        json.dump(results, f, indent=1)
    print(f"wrote {json_path}")


if __name__ == "__main__":
    main()
